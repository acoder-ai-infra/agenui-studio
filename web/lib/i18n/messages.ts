/**
 * UI message catalog for the management console.
 *
 * `zh` is the source of truth for the key set: `MessageKey` is derived from it,
 * and every other locale is typed as a complete `Record<MessageKey, string>`.
 * A missing or misspelled translation is therefore a type error, not a string
 * that silently falls back at runtime.
 *
 * Keys are grouped by the surface they belong to (`nav.*`, `space.*`, ...);
 * `common.*` holds labels shared by several pages.
 * Placeholders use `{name}` and are substituted by `format` below.
 *
 * Deliberately NOT in this catalog:
 *  - prompt text sent to the model (translating it would change Agent input);
 *  - strings matched against backend values (translating them breaks logic);
 *  - progress copy, which the backend owns via `progress_activity` frames.
 */

